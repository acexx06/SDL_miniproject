package com.hms.bench;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;

/** Writes docs/TEST_REPORT.md: the base system and the final scaled system under the same load, side by side. */
public final class CompareReport {

    /** Operations shown in the per-operation tables, with readable names. */
    static final Map<String, String> OPERATIONS = new LinkedHashMap<>();

    static {
        OPERATIONS.put("SUGGEST_DOCTOR", "Doctor suggestions");
        OPERATIONS.put("SEARCH_DOCTOR", "Doctor search");
        OPERATIONS.put("SUGGEST_MEDICINE", "Medicine suggestions");
        OPERATIONS.put("MY_RECORDS", "My records");
        OPERATIONS.put("MY_PROFILE", "My profile");
        OPERATIONS.put("MY_APPOINTMENTS", "My appointments");
        OPERATIONS.put("VIEW_SLOTS", "Doctor's free slots");
        OPERATIONS.put("MY_BILLS", "My bills");
        OPERATIONS.put("BOOK_APPOINTMENT", "Book appointment");
        OPERATIONS.put("PAY_BILL", "Pay bill");
        OPERATIONS.put("EMERGENCY", "Emergency request");
        OPERATIONS.put("LOGIN", "Login");
    }

    private final Map<String, Object> data;
    private final StringBuilder out = new StringBuilder();

    public CompareReport(Map<String, Object> data) {
        this.data = data;
    }

    private void line(String text) {
        out.append(text).append('\n');
    }

    private void table(List<String> headers, List<List<String>> rows) {
        line("| " + String.join(" | ", headers) + " |");
        line("|" + " --- |".repeat(headers.size()));
        rows.forEach(r -> line("| " + String.join(" | ", r) + " |"));
        line("");
    }

    private static String n(double v) {
        if (v == Math.rint(v) && Math.abs(v) < 1e15) {
            return String.format(Locale.ROOT, "%,d", (long) v);
        }
        return String.format(Locale.ROOT, Math.abs(v) >= 100 ? "%,.0f" : Math.abs(v) >= 10 ? "%,.1f" : "%,.2f", v);
    }

    private static String pct(double fraction) {
        return String.format(Locale.ROOT, "%.2f%%", fraction * 100);
    }

    /** "12× faster" or "1.3× slower", comparing the scaled value with the base value (lower is better). */
    static String faster(double base, double scaled) {
        if (base <= 0 || scaled <= 0) {
            return "—";
        }
        double ratio = base / scaled;
        if (Math.abs(ratio - 1) < 0.05) {
            return "about the same";
        }
        return ratio > 1 ? String.format(Locale.ROOT, "**%s× faster**", ratio >= 10 ? n(Math.round(ratio)) : String.format(Locale.ROOT, "%.1f", ratio))
                : String.format(Locale.ROOT, "%.1f× slower", 1 / ratio);
    }

    private List<Map<String, Object>> rows(String mode) {
        List<Map<String, Object>> value = Json.at(data, mode);
        return value == null ? List.of() : value;
    }

    private static String levelName(Map<String, Object> level) {
        String name = (String) level.get("level");
        return Character.toUpperCase(name.charAt(0)) + name.substring(1) + " (" + n(Json.num(level, "users")) + " users)";
    }

    public String render() {
        List<Map<String, Object>> base = rows("base");
        List<Map<String, Object>> scaled = rows("scaled");
        Map<String, Object> setup = Json.at(data, "setup");
        Map<String, Object> env = Json.at(data, "environment");
        int levels = Math.min(base.size(), scaled.size());

        line("# Base system and final scaled system: load test report");
        line("");
        line("This report is generated by `hms-bench report` from `results/compare.json`, which `hms-bench compare`");
        line("produces. To repeat it: `run.bat bench compare`, then `run.bat bench report`.");
        line("");
        if (env != null) {
            line("**Measured** " + env.get("measuredAt") + " on " + env.get("os") + ", " + env.get("logicalCores") + " logical cores, "
                    + env.get("memoryGb") + " GB RAM" + (env.get("powerSource") != null ? ", running on " + env.get("powerSource") : "")
                    + ". " + env.get("note")
                    + (Boolean.TRUE.equals(env.get("quickMode")) ? " **Quick mode: short runs, indicative only.**" : "")
                    + (Boolean.TRUE.equals(env.get("incomplete")) ? " **The run did not finish; missing levels are left out.**" : ""));
            line("");
        }

        line("## 1. What was compared");
        line("");
        line("Both runs use the same application, the same database contents, the same simulated users and the same");
        line("workload. Only the scaling components differ. They are switched off at run time for the base system,");
        line("so the comparison isolates their effect rather than comparing two different programs.");
        line("");
        table(List.of("", "Base system", "Final scaled system"), List.of(
                List.of("Checking the session on every request", "MongoDB query", "Key-value cache (3 servers, consistent hashing, 2 copies of each key)"),
                List.of("Reading a patient's profile, records, appointments, bills; a doctor's free slots", "MongoDB query", "Key-value cache; MongoDB only on a miss"),
                List.of("Doctor and medicine search, and suggestions while typing", "MongoDB pattern query on every keystroke", "In-memory autocomplete index (trie)"),
                List.of("Rate limiter", "Off", "On (token bucket per client and request type)"),
                List.of("Writes, ids, indexes, booking rules, crawled data", "Same", "Same")));

        line("## 2. Test setup");
        line("");
        if (setup != null) {
            line("- **Data:** " + n(Json.num(setup, "patients")) + " patients, " + n(Json.num(setup, "records")) + " medical records and "
                    + n(Json.num(setup, "doctors")) + " doctors in MongoDB.");
            List<?> users = Json.at(setup, "users");
            line("- **Load levels:** " + users + " concurrent users. Each user is a logged-in patient who performs an action, pauses "
                    + setup.get("thinkTimeMs") + " ms, and repeats.");
            line("- **Workload:** 85% reads and searches, 15% writes (bookings, payments, link sharing, emergencies, logins,");
            line("  registrations), the same mix as in [RESULTS.md](RESULTS.md) section 1.");
            line("- **Timing:** both configurations were exercised unmeasured first; then each level ran for "
                    + n(Json.num(setup, "warmupSeconds")) + " s of warm-up and " + n(Json.num(setup, "measureSeconds")) + " s of measurement.");
            line("- **Counting:** a booking refused because the slot was taken (HTTP 409) is a correct answer and counts as a success;");
            line("  timeouts, server errors and dropped connections count as errors.");
            line("");
        }

        line("## 3. Results");
        line("");
        List<List<String>> summary = new ArrayList<>();
        for (int i = 0; i < levels; i++) {
            Map<String, Object> b = base.get(i);
            Map<String, Object> s = scaled.get(i);
            summary.add(List.of(levelName(b), "Base", n(Json.num(b, "throughputRps")), n(Json.num(b, "latencyMs", "avg")), n(Json.num(b, "latencyMs", "p50")),
                    n(Json.num(b, "latencyMs", "p95")), n(Json.num(b, "latencyMs", "p99")), pct(Json.num(b, "errorRate")), n(Json.num(b, "resources", "appCpuCoresUsed"))));
            summary.add(List.of("", "**Scaled**", n(Json.num(s, "throughputRps")), n(Json.num(s, "latencyMs", "avg")), n(Json.num(s, "latencyMs", "p50")),
                    n(Json.num(s, "latencyMs", "p95")), n(Json.num(s, "latencyMs", "p99")), pct(Json.num(s, "errorRate")), n(Json.num(s, "resources", "appCpuCoresUsed"))));
        }
        table(List.of("Load", "System", "Throughput (req/s)", "Avg (ms)", "Median (ms)", "p95 (ms)", "p99 (ms)", "Errors", "App CPU (cores)"), summary);

        List<List<String>> gains = new ArrayList<>();
        for (int i = 0; i < levels; i++) {
            Map<String, Object> b = base.get(i);
            Map<String, Object> s = scaled.get(i);
            gains.add(List.of(levelName(b), faster(Json.num(b, "latencyMs", "avg"), Json.num(s, "latencyMs", "avg")),
                    faster(Json.num(b, "latencyMs", "p50"), Json.num(s, "latencyMs", "p50")),
                    faster(Json.num(b, "latencyMs", "p95"), Json.num(s, "latencyMs", "p95")),
                    n(Json.num(b, "throughputRps")) + " → " + n(Json.num(s, "throughputRps")) + " req/s"));
        }
        line("**Scaled compared with base:**");
        line("");
        table(List.of("Load", "Average", "Median", "95th percentile", "Throughput"), gains);
        line("![95th percentile response time, base and scaled](img/compare_p95.png)");
        line("");
        line("![Throughput, base and scaled](img/compare_throughput.png)");
        line("");

        if (levels > 0) {
            int top = levels - 1;
            Map<String, Object> b = base.get(top);
            Map<String, Object> s = scaled.get(top);
            line("### Operation by operation at the highest load (" + n(Json.num(b, "users")) + " users)");
            line("");
            List<List<String>> ops = new ArrayList<>();
            for (Map.Entry<String, String> op : OPERATIONS.entrySet()) {
                Object bo = Json.at(b, "perOperation", op.getKey());
                Object so = Json.at(s, "perOperation", op.getKey());
                if (bo == null || so == null) {
                    continue;
                }
                ops.add(List.of(op.getValue(), n(Json.num(bo, "avg")), n(Json.num(bo, "p95")), n(Json.num(so, "avg")), n(Json.num(so, "p95")),
                        faster(Json.num(bo, "avg"), Json.num(so, "avg"))));
            }
            table(List.of("Operation", "Base avg (ms)", "Base p95 (ms)", "Scaled avg (ms)", "Scaled p95 (ms)", "Scaled is"), ops);
            line("![Average response time per operation at the highest load](img/compare_ops.png)");
            line("");
        }

        line("### Resources used by the application");
        line("");
        List<List<String>> res = new ArrayList<>();
        for (int i = 0; i < levels; i++) {
            Map<String, Object> b = base.get(i);
            Map<String, Object> s = scaled.get(i);
            res.add(List.of(levelName(b), n(Json.num(b, "resources", "appCpuCoresUsed")), n(Json.num(s, "resources", "appCpuCoresUsed")),
                    n(Json.num(b, "resources", "heapUsedMbMax")), n(Json.num(s, "resources", "heapUsedMbMax")),
                    n(Json.num(b, "resources", "threadsMax")), n(Json.num(s, "resources", "threadsMax")), pct(Json.num(s, "cacheHitRatio"))));
        }
        table(List.of("Load", "CPU base (cores)", "CPU scaled (cores)", "Heap base (MB)", "Heap scaled (MB)", "Threads base", "Threads scaled",
                "Cache hit ratio (scaled)"), res);
        line("CPU and heap are the application process only. MongoDB and the load generator ran on the same machine and are");
        line("not included; in the base system much of the extra work happens inside MongoDB.");
        line("");

        line("## 4. Findings");
        line("");
        for (int i = 0; i < levels; i++) {
            Map<String, Object> b = base.get(i);
            Map<String, Object> s = scaled.get(i);
            String errors = Json.num(b, "errorRate") > 0 || Json.num(s, "errorRate") > 0
                    ? String.format(Locale.ROOT, " Errors: %s in the base system, %s in the scaled one.", pct(Json.num(b, "errorRate")), pct(Json.num(s, "errorRate")))
                    : " Neither system returned an error.";
            line("- **" + levelName(b) + ":** the 95th-percentile response time went from " + n(Json.num(b, "latencyMs", "p95")) + " ms to "
                    + n(Json.num(s, "latencyMs", "p95")) + " ms (" + faster(Json.num(b, "latencyMs", "p95"), Json.num(s, "latencyMs", "p95")).replace("**", "")
                    + "), and throughput from " + n(Json.num(b, "throughputRps")) + " to " + n(Json.num(s, "throughputRps")) + " requests per second." + errors);
        }
        if (levels > 0) {
            Map<String, Object> b = base.get(levels - 1);
            Map<String, Object> s = scaled.get(levels - 1);
            if (Json.at(b, "perOperation", "LOGIN") != null && Json.at(s, "perOperation", "LOGIN") != null) {
                line("- **The slowest 1% of requests are logins in both systems.** A login computes a deliberately slow BCrypt password");
                line("  hash, which neither configuration changes: at the highest load a login averaged " + n(Json.num(b, "perOperation", "LOGIN", "avg"))
                        + " ms in the base system and " + n(Json.num(s, "perOperation", "LOGIN", "avg")) + " ms in the scaled one, which was");
                line("  also processing " + String.format(Locale.ROOT, "%.1f", Json.num(s, "throughputRps") / Math.max(1, Json.num(b, "throughputRps")))
                        + " times as many requests. That is why the 99th percentile barely differs, or is higher for the scaled system, while");
                line("  the median and the 95th percentile improve.");
            }
        }
        line("");
        line("Throughput is set mostly by how many users there are and how long they pause, so the two systems serve similar");
        line("request rates until one of them runs out of capacity; the difference shows first in response times. Where the");
        line("base system's throughput falls below the scaled system's, it has reached its limit: its users spend their time");
        line("waiting for answers instead of making new requests. The causes of the difference, component by component,");
        line("are measured separately in [RESULTS.md](RESULTS.md) sections 3 and 5.");
        return out.toString();
    }
}
